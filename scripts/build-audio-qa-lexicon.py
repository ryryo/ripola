#!/usr/bin/env python3
"""Offline, deterministic extraction of bounded spelling alternatives from pinned CC0 data."""
import hashlib
import itertools
import json
import math
from pathlib import Path
import re
import sys

REVISION = 'fb59dcd77b9b5608e6dbb3df97440336e1902fed'
SHA256 = '91a146b9cf300a644689e972e54869078a3d9835df3b1bf5c66af06e64fa10ad'


def build(path):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError('Input does not match the pinned accepted-spellings dataset')
    entries = {}

    def add(surface, alternatives):
        if not surface or len(surface) > 24 or not re.fullmatch(r'[一-鿿々ぁ-ゖァ-ヶーA-Za-z0-9]+', surface):
            return
        values = entries.setdefault(surface, set())
        values.update(a for a in alternatives if a and a != surface and len(a) <= 48
                      and re.fullmatch(r'[一-鿿々ぁ-ゖァ-ヶーA-Za-z0-9]+', a))

    for line in data.decode('utf-8').splitlines():
        for segment in json.loads(line)['segments']:
            pieces = segment['pieces']
            # Contiguous annotated characters form compound readings; kana end a compound.
            run = []
            for piece in pieces + [{'text': '', 'readings': []}]:
                text, readings = piece['text'], piece['readings']
                add(text, readings)
                if readings and re.fullmatch(r'[一-鿿々]+', text):
                    run.append(piece)
                    continue
                if len(run) > 1:
                    choices = [p['readings'] for p in run]
                    if all(choices) and math.prod(map(len, choices)) <= 16:
                        add(''.join(p['text'] for p in run), [''.join(p) for p in itertools.product(*choices)])
                run = []
            if segment['spellings']:
                surface = ''.join(p['text'] for p in pieces)
                variants = [surface, *segment['spellings']]
                for variant in variants:
                    add(variant, variants)
    entries = {k: sorted(v) for k, v in sorted(entries.items()) if v and len(v) <= 16}
    destination = Path(__file__).resolve().parents[1] / 'apps/web/src/generation/audio-quality/spellings.generated.ts'
    destination.parent.mkdir(parents=True, exist_ok=True)
    header = '// Generated by scripts/build-audio-qa-lexicon.py; see docs/licenses/audio-qa-data.md.\n'
    header += f'export const SPELLINGS_VERSION = "common-voice-ja-8.0-{REVISION[:12]}-extract-v1";\n'
    header += 'export const SPELLINGS: Record<string, readonly string[]> = {\n'
    rows = [f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)},' for k, v in entries.items()]
    destination.write_text(header + '\n'.join(rows) + '\n};\n', encoding='utf-8')
    print(json.dumps({'entries': len(entries), 'sourceSha256': SHA256, 'revision': REVISION}))


if __name__ == '__main__':
    build(sys.argv[1])
